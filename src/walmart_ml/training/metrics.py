"""Regression metrics for model evaluation, logged to MLflow."""

import logging
from math import sqrt

import numpy as np
from numpy.typing import ArrayLike
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    median_absolute_error,
    r2_score
)
import mlflow

LOGGER = logging.getLogger(__name__)


def mape(y_true: ArrayLike, y_pred: ArrayLike) -> float:
    """Calculate the Mean Absolute Percentage Error (MAPE).

    MAPE measures the average prediction error as a percentage of the actual
    values. It is useful for understanding model error in relative terms rather
    than absolute sales values.

    Any zero actual values are replaced with a very small number to avoid
    division by zero.

    Args:
        y_true: Actual target values.
        y_pred: Predicted target values.

    Returns:
        float: Mean absolute percentage error.
    """
    actual = np.asarray(y_true, dtype=float)
    predicted = np.asarray(y_pred, dtype=float)
    denom = np.where(actual == 0, 1e-9, actual)
    return float(np.mean(np.abs((actual - predicted) / denom)) * 100.0)


def calculate_regression_metrics(y_test: ArrayLike, preds: ArrayLike) -> None:
    """Calculate, log, and record regression metrics for model evaluation.

    Compares the model predictions against the actual test target values and
    calculates several regression metrics, including MAE, RMSE, MAPE, R2,
    Median Absolute Error, Bias, and WAPE. The results are logged for the
    pipeline output and recorded in MLflow for experiment tracking.

    Args:
        y_test: Actual target values from the test dataset.
        preds: Predicted target values generated by the model.
    """

    mae = mean_absolute_error(y_test, preds)
    rmse = sqrt(mean_squared_error(y_test, preds))
    mp = mape(y_test, preds)
    r2 = r2_score(y_test, preds)
    medae = median_absolute_error(y_test, preds)
    actual = np.asarray(y_test, dtype=float)
    predicted = np.asarray(preds, dtype=float)
    bias = float(np.mean(predicted - actual))
    wape = float(np.sum(np.abs(actual - predicted)) / np.sum(np.abs(actual)) * 100)

    LOGGER.info("MAE: %s", f"{mae:,.0f}")
    LOGGER.info("RMSE: %s", f"{rmse:,.0f}")
    LOGGER.info("MAPE: %.2f%%", mp)
    LOGGER.info("R2: %.4f", r2)
    LOGGER.info("Median AE: %s", f"{medae:,.0f}")
    LOGGER.info("BIAS: %s", f"{bias:,.2f}")
    LOGGER.info("WAPE: %.2f%%", wape)

    mlflow.log_metric("MAE", mae)
    mlflow.log_metric("RMSE", rmse)
    mlflow.log_metric("MAPE", mp)
    mlflow.log_metric("R2", r2)
    mlflow.log_metric("Median_AE", medae)
    mlflow.log_metric("Bias", bias)
    mlflow.log_metric("WAPE", wape)
